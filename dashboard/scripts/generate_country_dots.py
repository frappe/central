"""Write src/lib/countryDots.ts: the dots of WorldDots.vue that fall in each country.

Usage: python3 scripts/generate_country_dots.py ne_50m_admin_0_countries.geojson

The borders are Natural Earth's public domain Admin 0 countries:
https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson
"""

import json
import re
import sys
from pathlib import Path

DASHBOARD = Path(__file__).resolve().parent.parent
WORLD_DOTS = DASHBOARD / "src/components/servers/WorldDots.vue"
OUTPUT = DASHBOARD / "src/lib/countryDots.ts"

# The projection of lib/serverMap.ts and the dot pitch of WorldDots.vue.
MAP_WIDTH, MAP_HEIGHT = 879, 443
LAT_TOP, LAT_BOTTOM = 83, -56
PITCH = 3.66
# The first dot of the grid, on both axes.
ORIGIN = 1.83
RUN = re.compile(r"M([\d.]+) ([\d.]+)(?:H([\d.]+)|h\.01)")


def read_dots() -> list[tuple[float, float]]:
	path = re.search(r"const D =\s*'([^']+)'", WORLD_DOTS.read_text()).group(1)
	dots = []
	for start, y, end in RUN.findall(path):
		count = round((float(end or start) - float(start)) / PITCH) + 1
		dots += [(round(float(start) + index * PITCH, 2), float(y)) for index in range(count)]
	return dots


def to_degrees(x: float, y: float) -> tuple[float, float]:
	return x / MAP_WIDTH * 360 - 180, LAT_TOP - y / MAP_HEIGHT * (LAT_TOP - LAT_BOTTOM)


def is_inside(lng: float, lat: float, ring: list[list[float]]) -> bool:
	inside = False
	for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1], strict=True):
		if (y1 > lat) != (y2 > lat) and lng < (x2 - x1) * (lat - y1) / (y2 - y1) + x1:
			inside = not inside
	return inside


def read_countries(geojson: Path) -> list[tuple[str, list, tuple, tuple]]:
	"""Each country's ISO code, polygons, bounding box and label point."""
	countries = []
	for feature in json.loads(geojson.read_text())["features"]:
		properties, geometry = feature["properties"], feature["geometry"]
		code = properties["ISO_A2_EH"] if properties["ISO_A2_EH"] != "-99" else properties["ISO_A2"]
		if code == "-99":
			continue

		polygons = (
			geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
		)
		points = [point for polygon in polygons for point in polygon[0]]
		box = (
			min(p[0] for p in points),
			min(p[1] for p in points),
			max(p[0] for p in points),
			max(p[1] for p in points),
		)
		countries.append((code, polygons, box, (properties["LABEL_X"], properties["LABEL_Y"])))
	return countries


def find_country(lng: float, lat: float, countries: list) -> str | None:
	for code, polygons, (west, south, east, north), _label in countries:
		if not (west <= lng <= east and south <= lat <= north):
			continue
		for outer, *holes in polygons:
			if is_inside(lng, lat, outer) and not any(is_inside(lng, lat, hole) for hole in holes):
				return code
	return None


def locate(x: float, y: float, countries: list) -> str | None:
	"""The country under a dot. A coastal dot just off the border takes the country beside it."""
	half = PITCH / 2
	for dx, dy in ((0, 0), (half, 0), (-half, 0), (0, half), (0, -half)):
		if code := find_country(*to_degrees(x + dx, y + dy), countries):
			return code
	return None


def to_grid(lng: float, lat: float) -> tuple[float, float]:
	"""The grid dot nearest a place."""
	x = (lng + 180) / 360 * MAP_WIDTH
	y = (LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM) * MAP_HEIGHT
	return tuple(round(ORIGIN + round((value - ORIGIN) / PITCH) * PITCH, 2) for value in (x, y))


def to_path(dots: list[tuple[float, float]]) -> str:
	"""Dots as horizontal runs, in the path format of WorldDots.vue."""
	runs, previous = [], None
	for x, y in sorted(dots, key=lambda dot: (dot[1], dot[0])):
		if previous and previous[1] == y and abs(x - previous[0] - PITCH) < 0.05:
			runs[-1][2] = x
		else:
			runs.append([x, y, x])
		previous = (x, y)
	return "".join(f"M{start:g} {y:g}" + (f"H{end:g}" if end != start else "h.01") for start, y, end in runs)


def main() -> None:
	countries = read_countries(Path(sys.argv[1]))
	by_country: dict[str, list] = {}
	for x, y in read_dots():
		if code := locate(x, y, countries):
			by_country.setdefault(code, []).append((x, y))

	# A country too small for the grid still gets one dot, so it can show on the map.
	for code, _polygons, _box, label in countries:
		by_country.setdefault(code, [to_grid(*label)])

	lines = [f"\t{code}: '{to_path(dots)}'," for code, dots in sorted(by_country.items())]
	OUTPUT.write_text(
		"// Generated by scripts/generate_country_dots.py from Natural Earth borders. Do not edit.\n"
		"// The dots of WorldDots.vue in each country, by ISO code, in the same path format.\n"
		"export const COUNTRY_DOTS: Record<string, string> = {\n" + "\n".join(lines) + "\n}\n"
	)
	print(f"{len(by_country)} countries")


if __name__ == "__main__":
	main()
